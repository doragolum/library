-- Нічого не видаляється і не переписується; відкат — drop column owner_id і drop table app_users.
create table app_users (
  id          bigint generated by default as identity primary key,
  name        text,
  role        text not null default 'user' check (role in ('owner','user')),
  tg_id       bigint unique,          -- вхід через Телеграм (етап 4)
  email       text unique,            -- вхід кодом з пошти (етап 4)
  invited_by  bigint references app_users(id),
  created_at  timestamptz not null default now()
);
alter table app_users enable row level security;  -- без політик: усе через функції, як і решта
insert into app_users (id, name, role) values (1, 'Даша', 'owner');
