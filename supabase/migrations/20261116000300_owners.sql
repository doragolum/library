-- особисті записи: власниця за замовчуванням — 1 (Даша), поки друзів немає
alter table books      add column owner_id bigint not null default 1 references app_users(id);
alter table series     add column owner_id bigint not null default 1 references app_users(id);
alter table wish_found add column owner_id bigint not null default 1 references app_users(id);
alter table log        add column owner_id bigint not null default 1 references app_users(id);
